"""Taxonomy parametric extras (72 problems).

These are the parametric F1/F2/F3/F4/F6/F7 problems whose per-problem
RT numbers appear in SORCAR_FAMILY_TAXONOMY.md but whose definitions
were generated by a cluster-only script and never committed. This
module reconstructs them faithfully from the taxonomy's own shape +
reduce-op annotations so that `--problem <taxonomy_name>` resolves for
the measured-strat re-run.

Faithfulness contract (per problem): identical tensor shape, identical
reduce op, identical baseline collective count (so the Phase-1 sim
baseline cost matches), and identical optimal structure (one surviving
AR for F1/F2/F4/F6/F7; algebraic zero for F3). Coefficient values are
chosen deterministically; only the builtin==reference agreement matters
for correctness, and both are generated from the same spec here.
"""
