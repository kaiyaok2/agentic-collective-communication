def _mk_1d_scaled(name, coefs, N=65536):
    """K inline SUM-ARs of one 1-D input x, combined as sum(c_i * AR(x)).

    Result = (sum coefs) * AR(x). If sum(coefs)==0 this is an algebraic
    zero (F3); otherwise one surviving AR (F1/F2)."""
    total = float(sum(coefs))

    def _ref(inputs, world_size):
        ax = sum(inp['x'] for inp in inputs)
        return [(total * ax).clone() for _ in range(world_size)]

    def _gen(world_size, pattern='uniform', shard_size=None, seed=0):
        torch.manual_seed(seed)
        pra = [{'x': torch.randn(N) * (r + 1), 'N': N} for r in range(world_size)]
        return {'per_rank_args': pra, 'shared_args': {},
                'expected': _ref(pra, world_size)}

    def _call(fn, args, s, r, w, nd, cpd, xm, tm, num_nodes=1):
        return fn(args['x'], args['N'], r, w, nd, cpd, xm, tm, num_nodes=num_nodes)

    sig = (f"def {name}_fn(x, N, rank, world_size, num_devices,\n"
           f"                 cores_per_device, xm, torch, num_nodes=1):")
    doc = f"Local x (N,). N={N}. Baseline issues {len(coefs)} inline SUM-ARs of x."
    body_lines = [f"def {name}_fn(x, N, rank, world_size, num_devices,",
                  "                 cores_per_device, xm, torch, num_nodes=1):",
                  "    acc = None"]
    for c in coefs:
        body_lines.append(f"    t = {c!r} * xm.all_reduce(xm.REDUCE_SUM, x)")
        body_lines.append("    acc = t if acc is None else acc + t")
    body_lines.append("    return acc")
    builtin = {name: "\n".join(body_lines) + "\n"}

    register_problem(CollectiveProblem(
        name=name, display_name=name, evolved_fn_name=f"{name}_fn",
        signature=sig, signature_doc=doc, reference_fn=_ref,
        generate_test_case=_gen, call_candidate=_call,
        builtin_templates=builtin))


def _mk_perrow(name, M, N, op='SUM'):
    """Per-row loop: M inline ARs (one per row) of a (M, N) tensor.
    Optimal = 1 full-tensor AR. Baseline = M row-ARs."""
    red = {'SUM': 'REDUCE_SUM', 'MAX': 'REDUCE_MAX', 'MIN': 'REDUCE_MIN'}[op]

    def _ref(inputs, world_size):
        xs = [inp['x'] for inp in inputs]
        if op == 'SUM':
            res = sum(xs)
        else:
            res = xs[0]
            fn = torch.maximum if op == 'MAX' else torch.minimum
            for x in xs[1:]:
                res = fn(res, x)
        return [res.clone() for _ in range(world_size)]

    def _gen(world_size, pattern='uniform', shard_size=None, seed=0):
        torch.manual_seed(seed)
        pra = [{'x': torch.randn(M, N) * (r + 1)} for r in range(world_size)]
        return {'per_rank_args': pra, 'shared_args': {},
                'expected': _ref(pra, world_size)}

    def _call(fn, args, s, r, w, nd, cpd, xm, tm, num_nodes=1):
        return fn(args['x'], r, w, nd, cpd, xm, tm, num_nodes=num_nodes)

    sig = (f"def {name}_fn(x, rank, world_size, num_devices,\n"
           f"                 cores_per_device, xm, torch, num_nodes=1):")
    doc = f"Local x ({M}, {N}). Baseline AR({op}) per row ({M} collectives)."
    builtin = {name: (
        f"def {name}_fn(x, rank, world_size, num_devices,\n"
        f"                 cores_per_device, xm, torch, num_nodes=1):\n"
        f"    rows = [xm.all_reduce(xm.{red}, x[m]) for m in range(x.shape[0])]\n"
        f"    return torch.stack(rows, dim=0)\n")}

    register_problem(CollectiveProblem(
        name=name, display_name=name, evolved_fn_name=f"{name}_fn",
        signature=sig, signature_doc=doc, reference_fn=_ref,
        generate_test_case=_gen, call_candidate=_call,
        builtin_templates=builtin))


