def _mk_slab(name, n_slabs, slab_N, scaled=False):
    """F7: contiguous slabs of a 1-D buffer AR'd separately then cat'd.
    Optimal = 1 AR of the whole buffer, slice the output."""
    N = n_slabs * slab_N
    coefs = [float(i + 1) if scaled else 1.0 for i in range(n_slabs)]

    def _ref(inputs, world_size):
        ax = sum(inp['x'] for inp in inputs)
        parts = [coefs[i] * ax[i * slab_N:(i + 1) * slab_N] for i in range(n_slabs)]
        return [torch.cat(parts).clone() for _ in range(world_size)]

    def _gen(world_size, pattern='uniform', shard_size=None, seed=0):
        torch.manual_seed(seed)
        pra = [{'x': torch.randn(N) * (r + 1)} for r in range(world_size)]
        return {'per_rank_args': pra, 'shared_args': {},
                'expected': _ref(pra, world_size)}

    def _call(fn, args, s, r, w, nd, cpd, xm, tm, num_nodes=1):
        return fn(args['x'], r, w, nd, cpd, xm, tm, num_nodes=num_nodes)

    sig = (f"def {name}_fn(x, rank, world_size, num_devices,\n"
           f"                 cores_per_device, xm, torch, num_nodes=1):")
    doc = (f"Local x ({N},) = {n_slabs} contiguous slabs of {slab_N}. "
           f"Baseline ARs each slab separately then cat.")
    body = [f"def {name}_fn(x, rank, world_size, num_devices,",
            "                 cores_per_device, xm, torch, num_nodes=1):",
            f"    n_slabs, slab_N = {n_slabs}, {slab_N}",
            "    parts = []",
            "    for i in range(n_slabs):",
            "        s = xm.all_reduce(xm.REDUCE_SUM, x[i*slab_N:(i+1)*slab_N])",
            f"        parts.append(s * {'(i + 1)' if scaled else '1.0'})",
            "    return torch.cat(parts)"]
    builtin = {name: "\n".join(body) + "\n"}

    register_problem(CollectiveProblem(
        name=name, display_name=name, evolved_fn_name=f"{name}_fn",
        signature=sig, signature_doc=doc, reference_fn=_ref,
        generate_test_case=_gen, call_candidate=_call,
        builtin_templates=builtin))


def _mk_perrow_mixed(name, M, N):
    """F6 compound: per-row AR_MAX - AR_MIN over a (M, N) tensor.
    2M collectives -> 2 full-tensor collectives."""
    def _ref(inputs, world_size):
        xs = [inp['x'] for inp in inputs]
        mx = xs[0].clone()
        mn = xs[0].clone()
        for x in xs[1:]:
            mx = torch.maximum(mx, x)
            mn = torch.minimum(mn, x)
        return [(mx - mn).clone() for _ in range(world_size)]

    def _gen(world_size, pattern='uniform', shard_size=None, seed=0):
        torch.manual_seed(seed)
        pra = [{'x': torch.randn(M, N) * (r + 1)} for r in range(world_size)]
        return {'per_rank_args': pra, 'shared_args': {},
                'expected': _ref(pra, world_size)}

    def _call(fn, args, s, r, w, nd, cpd, xm, tm, num_nodes=1):
        return fn(args['x'], r, w, nd, cpd, xm, tm, num_nodes=num_nodes)

    sig = (f"def {name}_fn(x, rank, world_size, num_devices,\n"
           f"                 cores_per_device, xm, torch, num_nodes=1):")
    doc = (f"Local x ({M}, {N}). Baseline per-row AR_MAX(x[m]) - AR_MIN(x[m]) "
           f"({2 * M} collectives).")
    builtin = {name: (
        f"def {name}_fn(x, rank, world_size, num_devices,\n"
        f"                 cores_per_device, xm, torch, num_nodes=1):\n"
        f"    rows = []\n"
        f"    for m in range(x.shape[0]):\n"
        f"        mx = xm.all_reduce(xm.REDUCE_MAX, x[m])\n"
        f"        mn = xm.all_reduce(xm.REDUCE_MIN, x[m])\n"
        f"        rows.append(mx - mn)\n"
        f"    return torch.stack(rows, dim=0)\n")}

    register_problem(CollectiveProblem(
        name=name, display_name=name, evolved_fn_name=f"{name}_fn",
        signature=sig, signature_doc=doc, reference_fn=_ref,
        generate_test_case=_gen, call_candidate=_call,
        builtin_templates=builtin))


def _mk_mixmaxmin(name, K=8, N=4096):
    """F6: K alternating scaled AR_MAX / AR_MIN of a 1-D input.
    2K collectives -> 2 (one MAX, one MIN)."""
    cmax = [float(i + 1) * 0.1 for i in range(K)]
    cmin = [float(i + 1) * 0.05 for i in range(K)]
    smax, smin = float(sum(cmax)), float(sum(cmin))

    def _ref(inputs, world_size):
        xs = [inp['x'] for inp in inputs]
        mx = xs[0].clone()
        mn = xs[0].clone()
        for x in xs[1:]:
            mx = torch.maximum(mx, x)
            mn = torch.minimum(mn, x)
        return [(smax * mx + smin * mn).clone() for _ in range(world_size)]

    def _gen(world_size, pattern='uniform', shard_size=None, seed=0):
        torch.manual_seed(seed)
        pra = [{'x': torch.randn(N) * (r + 1)} for r in range(world_size)]
        return {'per_rank_args': pra, 'shared_args': {},
                'expected': _ref(pra, world_size)}

    def _call(fn, args, s, r, w, nd, cpd, xm, tm, num_nodes=1):
        return fn(args['x'], r, w, nd, cpd, xm, tm, num_nodes=num_nodes)

    sig = (f"def {name}_fn(x, rank, world_size, num_devices,\n"
           f"                 cores_per_device, xm, torch, num_nodes=1):")
    doc = (f"Local x ({N},). Baseline interleaves {K} scaled AR_MAX and {K} "
           f"scaled AR_MIN of x ({2 * K} collectives).")
    body = [f"def {name}_fn(x, rank, world_size, num_devices,",
            "                 cores_per_device, xm, torch, num_nodes=1):",
            "    acc = None"]
    for i in range(K):
        body.append(f"    a = {cmax[i]!r} * xm.all_reduce(xm.REDUCE_MAX, x)")
        body.append("    acc = a if acc is None else acc + a")
        body.append(f"    b = {cmin[i]!r} * xm.all_reduce(xm.REDUCE_MIN, x)")
        body.append("    acc = acc + b")
    body.append("    return acc")
    builtin = {name: "\n".join(body) + "\n"}

    register_problem(CollectiveProblem(
        name=name, display_name=name, evolved_fn_name=f"{name}_fn",
        signature=sig, signature_doc=doc, reference_fn=_ref,
        generate_test_case=_gen, call_candidate=_call,
        builtin_templates=builtin))


# ------------------------------------------------------------------
# Coefficient builders for the inline-AR families.
# ------------------------------------------------------------------
def _plain(k):            # k inline ARs, all +1  -> k * AR(x)
    return [1.0] * k

def _altsign(k):          # coefs (-1)^i * (i+1) -> nonzero, one surviving AR
    return [((-1.0) ** i) * (i + 1) for i in range(k)]

def _alt_unit(k):         # +1,-1,+1,... but forced nonzero via last term
    c = [1.0 if i % 2 == 0 else -1.0 for i in range(k)]
    if abs(sum(c)) < 1e-9:
        c[-1] += 1.0      # break the exact cancellation -> F2 (not F3)
    return c

def _algzero(k):          # coefs sum to exactly 0 -> algebraic zero (F3)
    c = [float(i + 1) for i in range(k - 1)]
    c.append(-float(sum(c)))
    return c

def _scaled_with_zeros(k):  # F1: distinct scales, some cancel, net nonzero
    c = []
    for i in range(k):
        c.append(float(i + 1))
        if i % 2 == 1:
            c.append(-float(i))       # partial cancellation ("w/ zeros")
    return c[:k] if len(c) >= k else c


