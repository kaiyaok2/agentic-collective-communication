#!/usr/bin/env python3
"""features.py — cheap structural features of an HLO module (from the HloModuleProto the compiler receives).

Uses hlo_pb2 generated by protoc from openxla's xla/service/hlo.proto (see setup: /home/ubuntu/hloproto). Falls back to
the HLO text saved at capture time if the proto bindings are unavailable.
Features: instruction count, computation count, opcode histogram, parameter/output/total tensor bytes, largest tensor,
dtype histogram, dot/conv FLOPs estimate, distinct shapes, max rank, control-flow and collective counts, proto bytes.
"""
import os, sys, re, json, math, collections
sys.path.insert(0, "/home/ubuntu/hloproto/gen")
try:
    from xla.service import hlo_pb2
    HAVE_PB = True
except Exception:
    HAVE_PB = False

DTYPE_BYTES = {"PRED": 1, "S8": 1, "U8": 1, "S16": 2, "U16": 2, "F16": 2, "BF16": 2, "S32": 4, "U32": 4, "F32": 4, "S64": 8, "U64": 8, "F64": 8, "C64": 8, "C128": 16,
               "F8E5M2": 1, "F8E4M3FN": 1, "F8E4M3": 1, "F8E5M2FNUZ": 1, "F8E4M3FNUZ": 1, "S4": 1, "U4": 1, "TOKEN": 0, "TUPLE": 0, "OPAQUE_TYPE": 0}

def _shape_info(shape, pt_name):
    """-> list of (dtype, dims) leaves"""
    et = pt_name(shape.element_type)
    if et == "TUPLE": return [x for s in shape.tuple_shapes for x in _shape_info(s, pt_name)]
    return [(et, list(shape.dimensions))]

def _bytes(leaves): return sum(DTYPE_BYTES.get(dt, 4) * (math.prod(d) if d else 1) for dt, d in leaves)

def features_from_pb(path):
    from xla import xla_data_pb2
    pt_name = lambda v: xla_data_pb2.PrimitiveType.Name(v)
    mod = hlo_pb2.HloModuleProto(); mod.ParseFromString(open(path, "rb").read())
    f = collections.OrderedDict(); ops = collections.Counter(); dtypes = collections.Counter(); shapes = set()
    n_instr = 0; total_bytes = 0; largest = 0; max_rank = 0; dot_flops = 0.0; conv_flops = 0.0; elem_bytes = 0
    entry = {c.id: c for c in mod.computations}.get(mod.entry_computation_id)
    for comp in mod.computations:
        for ins in comp.instructions:
            n_instr += 1; ops[ins.opcode] += 1
            leaves = _shape_info(ins.shape, pt_name); b = _bytes(leaves); total_bytes += b; largest = max(largest, b)
            for dt, d in leaves: dtypes[dt] += 1; shapes.add((dt, tuple(d))); max_rank = max(max_rank, len(d))
            if ins.opcode == "dot":
                out = math.prod(leaves[0][1]) if leaves and leaves[0][1] else 1
                # contracted size from first operand: operand dims / batch+free dims ~ approximate via operand shapes unavailable here; use dot_dimension_numbers
                try:
                    lhs_contract = list(ins.dot_dimension_numbers.lhs_contracting_dimensions)
                    opnd = {i.id: i for i in comp.instructions}
                    lhs = opnd.get(ins.operand_ids[0]) if ins.operand_ids else None
                    k = math.prod(lhs.shape.dimensions[i] for i in lhs_contract) if lhs is not None else 1
                except Exception: k = 1
                dot_flops += 2.0 * out * k
            elif ins.opcode == "convolution":
                out = math.prod(leaves[0][1]) if leaves and leaves[0][1] else 1
                try:
                    opnd = {i.id: i for i in comp.instructions}; rhs = opnd.get(ins.operand_ids[1])
                    kshape = list(rhs.shape.dimensions); dn = ins.convolution_dimension_numbers
                    k = math.prod(kshape[i] for i in dn.kernel_spatial_dimensions) * kshape[dn.kernel_input_feature_dimension]
                except Exception: k = 1
                conv_flops += 2.0 * out * k
            elif ins.opcode in ("add", "multiply", "subtract", "divide", "maximum", "minimum", "exponential", "tanh", "logistic", "select", "compare", "convert", "negate", "abs", "power", "rsqrt", "sqrt", "log"):
                elem_bytes += b
    params = [i for i in entry.instructions if i.opcode == "parameter"] if entry else []
    param_bytes = sum(_bytes(_shape_info(i.shape, pt_name)) for i in params)
    root = {i.id: i for i in entry.instructions}.get(entry.root_id) if entry else None
    out_bytes = _bytes(_shape_info(root.shape, pt_name)) if root is not None else 0
    f.update(dict(n_instructions=n_instr, n_computations=len(mod.computations), n_entry_instructions=len(entry.instructions) if entry else 0, n_params=len(params),
                  param_bytes=param_bytes, output_bytes=out_bytes, total_tensor_bytes=total_bytes, largest_tensor_bytes=largest, max_rank=max_rank,
                  n_distinct_shapes=len(shapes), dot_flops=dot_flops, conv_flops=conv_flops, elementwise_bytes=elem_bytes,
                  n_dot=ops["dot"], n_conv=ops["convolution"], n_reduce=ops["reduce"] + ops["reduce-window"], n_fusion=ops["fusion"], n_while=ops["while"], n_conditional=ops["conditional"],
                  n_custom_call=ops["custom-call"], n_collective=sum(ops[o] for o in ("all-reduce", "all-gather", "reduce-scatter", "all-to-all", "collective-permute", "all-reduce-start", "all-gather-start")),
                  n_gather=ops["gather"], n_scatter=ops["scatter"], n_sort=ops["sort"], n_dynamic_slice=ops["dynamic-slice"] + ops["dynamic-update-slice"], n_transpose=ops["transpose"],
                  n_reshape=ops["reshape"] + ops["bitcast"], n_broadcast=ops["broadcast"], n_concat=ops["concatenate"], n_slice=ops["slice"], n_pad=ops["pad"], n_iota=ops["iota"],
                  n_rng=ops["rng"] + ops["rng-bit-generator"], n_dtypes=len(dtypes), frac_bf16=round(dtypes["BF16"] / max(1, sum(dtypes.values())), 3), frac_f32=round(dtypes["F32"] / max(1, sum(dtypes.values())), 3),
                  proto_bytes=os.path.getsize(path), op_hist=dict(ops.most_common(40)), dtype_hist=dict(dtypes)))
    return f

_TXT = re.compile(r"^\s*(?:ROOT\s+)?%[\w.\-]+\s*=\s*(\(?[\w\[\],{}:\s]+\)?)\s+([\w\-]+)\(", re.M)

def features_from_text(path):
    txt = open(path, errors="ignore").read(); ops = collections.Counter(); total = 0; largest = 0; dtypes = collections.Counter()
    for m in _TXT.finditer(txt):
        shape, op = m.group(1), m.group(2); ops[op] += 1
        for dt, dims in re.findall(r"(\w+)\[([\d,]*)\]", shape):
            dtypes[dt.upper()] += 1; n = math.prod(int(x) for x in dims.split(",") if x) if dims else 1; b = n * DTYPE_BYTES.get(dt.upper(), 4); total += b; largest = max(largest, b)
    return dict(n_instructions=sum(ops.values()), n_computations=txt.count("\n}\n"), total_tensor_bytes=total, largest_tensor_bytes=largest, n_dot=ops["dot"], n_conv=ops["convolution"],
                n_reduce=ops["reduce"], n_while=ops["while"], n_custom_call=ops["custom-call"], n_dtypes=len(dtypes), op_hist=dict(ops.most_common(40)), dtype_hist=dict(dtypes), text_bytes=len(txt), from_text=True)

def features(hlo_pb=None, hlo_txt=None):
    if hlo_pb and HAVE_PB and os.path.exists(hlo_pb):
        try: return features_from_pb(hlo_pb)
        except Exception as e:
            err = str(e)[:200]
            if hlo_txt and os.path.exists(hlo_txt): r = features_from_text(hlo_txt); r["pb_err"] = err; return r
            return {"feat_err": err}
    if hlo_txt and os.path.exists(hlo_txt): return features_from_text(hlo_txt)
    return {"feat_err": "no input"}

if __name__ == "__main__":
    print("HAVE_PB", HAVE_PB)
    for p in sys.argv[1:]: print(p, json.dumps(features(hlo_pb=p if p.endswith(".pb") else None, hlo_txt=p if p.endswith(".txt") else None), indent=0)[:1500])
