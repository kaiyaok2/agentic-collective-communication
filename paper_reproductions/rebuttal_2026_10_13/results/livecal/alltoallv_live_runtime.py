"""
AllToAllV: Optimized implementation for AWS Trainium.

Generated by the LLM-guided algorithm evolution agent.
"""

import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_alltoallv():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_alltoallv(input_tensor, send_counts, recv_counts, max_chunk,
                      rank, world_size, num_devices, cores_per_device,
                      xm, torch, num_nodes=1):
    """Optimized all-gather with cheaper tensor extraction.
    
    Strategy:
    1. Uniform case: Use AG + reshape + single slice (avoid stack)
    2. Variable case: Minimal packing + AG + index_select
    """
    
    # Check if uniform case (all counts equal max_chunk)
    uniform_send = all(sc == max_chunk for sc in send_counts)
    uniform_recv = all(rc == max_chunk for rc in recv_counts)
    
    if uniform_send and uniform_recv:
        # Optimized uniform path: AG + reshape + single transpose extraction
        # Cost: 1 unsqueeze + 1 all_gather + 2 view + 1 slice
        gathered = xm.all_gather(input_tensor.unsqueeze(0), dim=0)
        # gathered shape: [world_size, world_size * max_chunk]
        reshaped = gathered.view(world_size, world_size, max_chunk)
        # reshaped[src, dst, :] contains data from src to dst
        # We want data from all sources to us (rank): reshaped[:, rank, :]
        
        # Extract column for this rank and flatten
        # Single slice operation instead of world_size slices + stack
        # Cost: 1 narrow + 1 view = ~17.9 + 1 = ~19us
        # vs 224 slices (224us) + stack (201.9us) = 425.9us
        result = reshaped[:, rank, :].reshape(-1)
        return result
    
    # Variable-length path: must pack and extract
    pack_size = world_size * max_chunk
    
    # Pack sends - create one buffer and fill
    # Cost: 1 zeros (~509us) + world_size slices
    packed = torch.zeros(pack_size, device=input_tensor.device, dtype=input_tensor.dtype)
    send_off = 0
    for i in range(world_size):
        sc = send_counts[i]
        if sc > 0:
            packed[i * max_chunk:i * max_chunk + sc] = input_tensor[send_off:send_off + sc]
        send_off += sc
    
    # All-gather: 1 collective (~100us dispatch + bandwidth)
    gathered = xm.all_gather(packed.unsqueeze(0), dim=0).view(-1)
    
    # Extract receives with index_select (single expensive op vs many ops)
    total_recv = sum(recv_counts)
    if total_recv == 0:
        return torch.zeros(0, device=input_tensor.device, dtype=input_tensor.dtype)
    
    # Build flat index in Python (cheap), create index tensor once
    flat_idx = []
    for src in range(world_size):
        count = recv_counts[src]
        if count > 0:
            base = src * pack_size + rank * max_chunk
            flat_idx.extend(range(base, base + count))
    
    if not flat_idx:
        return torch.zeros(0, device=input_tensor.device, dtype=input_tensor.dtype)
    
    # Cost: 1 tensor + 1 index_select = ~63.5 + 1044 = ~1107us
    idx_tensor = torch.tensor(flat_idx, device=input_tensor.device, dtype=torch.long)
    return torch.index_select(gathered, 0, idx_tensor)


