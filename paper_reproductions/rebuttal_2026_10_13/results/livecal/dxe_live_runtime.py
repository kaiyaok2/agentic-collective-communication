"""
Distributed Cross-Entropy (vocab-sharded): Optimized implementation for AWS Trainium.

Generated by the LLM-guided algorithm evolution agent.
"""

import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_dxe():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_dxe(logits_local, targets, V_local, rank, world_size, num_devices,
                cores_per_device, xm, torch, num_nodes=1):
    """Full-vocab all-gather then log-softmax + target-gather + mean.
    Semantically equivalent to baseline_ce in train_olmoe10b.py
    (xm.all_gather + F.cross_entropy), but expressed in primitive ops
    so the Phase-2 TrackedTensor sandbox accepts it (F.cross_entropy
    rejects TrackedTensor inputs). One xm.all_gather over (T, V_local)
    producing (T, V_total) on every rank, then a local log-softmax
    plus a per-token gather of the target logit. Substantially more
    cross-rank bytes per call than the 2-/3-AR families, but it IS
    what the OLMoE --ce baseline path runs end-to-end."""
    ll = logits_local.reshape(-1, V_local).contiguous()
    gathered = xm.all_gather(ll, dim=1)
    # log-softmax(gathered): subtract row-wise max for stability,
    # then log-sum-exp.
    gmax = gathered.max(dim=-1, keepdim=True).values
    shifted = gathered - gmax
    log_sum_exp = shifted.exp().sum(dim=-1).log() + gmax.squeeze(-1)
    tgt_flat = targets.reshape(-1)
    target_logit = gathered.gather(1, tgt_flat.unsqueeze(1)).squeeze(1)
    return (log_sum_exp - target_logit).mean()



# ================================================================
# Public API
# ================================================================

def dxe_loss(logits_local, targets, V_local):
    """Compute distributed cross-entropy on vocab-sharded logits."""
    if _rank is None:
        raise RuntimeError("Call init_dxe() first")
    return evolved_dxe(
        logits_local, targets, V_local, _rank, _world_size,
        _NUM_DEVICES, _CORES_PER_DEVICE, xm, torch, num_nodes=_NUM_NODES)

