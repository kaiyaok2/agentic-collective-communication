"""
FSDP-style sharded weight prefetch with microbatching: Optimized implementation for AWS Trainium.

Generated by the LLM-guided algorithm evolution agent.
"""

import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_fsdp_prefetch():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_fsdp_prefetch(shards, M, N_LAYERS, rank, world_size,
                          num_devices, cores_per_device, xm, torch, num_nodes=1):
    outs = [[None] * N_LAYERS for _ in range(M)]

    if world_size == 1:
        for m in range(M):
            for L in range(N_LAYERS):
                outs[m][L] = shards[m][L]
        return outs

    # Group (m, L) pairs by shard shape so we can bundle compatible ones.
    shape_to_items = {}
    shape_order = []
    for L in range(N_LAYERS):
        for m in range(M):
            shp = tuple(shards[m][L].shape)
            if shp not in shape_to_items:
                shape_to_items[shp] = []
                shape_order.append(shp)
            shape_to_items[shp].append((m, L))

    for shp in shape_order:
        items = shape_to_items[shp]
        n = len(items)
        if n == 1:
            m, L = items[0]
            outs[m][L] = xm.all_gather(shards[m][L], dim=-1)
            continue

        # Concatenate along dim 0 instead of stacking (avoids expensive stack).
        # Shards of shape shp; cat along dim 0 gives (n*shp[0], shp[1], ..., shp[-1]).
        tensors = [shards[m][L] for (m, L) in items]
        ndim = len(shp)
        if ndim == 0:
            # Scalar shards: must stack to create a dim.
            stacked = torch.stack(tensors, dim=0)
            gathered = xm.all_gather(stacked, dim=-1)
            parts = torch.split(gathered, 1, dim=0)
            for i in range(n):
                m, L = items[i]
                outs[m][L] = parts[i].squeeze(0)
        else:
            # Cat along dim 0 (non-sharded since shard dim is -1).
            # If ndim == 1, dim 0 IS the sharded dim, so we need a different approach.
            if ndim == 1:
                # Use cat along dim 0 still works but messes layout after AG.
                # Unsqueeze each to add a leading dim, then cat.
                # Unsqueeze is metadata-cheap. Then cat on dim 0.
                unsq = [t.unsqueeze(0) for t in tensors]
                catted = torch.cat(unsq, dim=0)  # shape (n, S)
                gathered = xm.all_gather(catted, dim=-1)  # (n, S*ws)
                parts = torch.split(gathered, 1, dim=0)
                for i in range(n):
                    m, L = items[i]
                    outs[m][L] = parts[i].squeeze(0)
            else:
                # ndim >= 2, shard dim is -1, dim 0 is independent.
                size0 = shp[0]
                catted = torch.cat(tensors, dim=0)  # (n*size0, ..., S)
                gathered = xm.all_gather(catted, dim=-1)  # (n*size0, ..., S*ws)
                parts = torch.split(gathered, size0, dim=0)
                for i in range(n):
                    m, L = items[i]
                    outs[m][L] = parts[i]

    return outs

