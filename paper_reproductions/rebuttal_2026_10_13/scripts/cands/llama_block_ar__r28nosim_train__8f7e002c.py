import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_llama_block_ar():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_llama_block(attn_partial, mlp_partial, rank, world_size,
                        num_devices, cores_per_device, xm, torch, num_nodes=1):
    """Fuse the two AR calls into a single all_reduce on a stacked tensor.

    Both attn_partial and mlp_partial have identical shape (B, S, DM) and dtype.
    By stacking along a new leading dimension we do ONE collective dispatch
    instead of two, saving ~100us of dispatch overhead plus reducing the
    number of bandwidth-limited ring passes.
    """
    if world_size == 1:
        return [attn_partial, mlp_partial]

    # Stack along new dim 0 -> shape (2, B, S, DM), same dtype/device.
    stacked = torch.stack([attn_partial, mlp_partial], dim=0)

    # Single fused all-reduce.
    reduced = xm.all_reduce(xm.REDUCE_SUM, stacked)

    # Split back into the two outputs (metadata-only ops).
    attn_full = reduced[0]
    mlp_full = reduced[1]

    return [attn_full, mlp_full]

