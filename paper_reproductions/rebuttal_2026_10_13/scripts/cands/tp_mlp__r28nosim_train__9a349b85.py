def init_tp_mlp():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_tp_mlp(partials, M, N_LAYERS, rank, world_size,
                   num_devices, cores_per_device, xm, torch, num_nodes=1):
    """Stack uniform partials for single all_reduce; fallback to cat for mixed shapes."""
    if world_size == 1:
        return [[partials[m][L] for L in range(N_LAYERS)] for m in range(M)]

    total = M * N_LAYERS
    if total == 1:
        return [[xm.all_reduce(xm.REDUCE_SUM, partials[0][0])]]

    # Check if all shapes are identical
    first_shape = partials[0][0].shape
    uniform = True
    for m in range(M):
        for L in range(N_LAYERS):
            if partials[m][L].shape != first_shape:
                uniform = False
                break
        if not uniform:
            break

    if uniform:
        # Flatten list and stack -- stack is metadata-light vs cat
        flat = []
        for m in range(M):
            for L in range(N_LAYERS):
                flat.append(partials[m][L])
        stacked = torch.stack(flat, dim=0)
        reduced = xm.all_reduce(xm.REDUCE_SUM, stacked)
        # Split back via narrow (metadata-only) or unbind
        outs = []
        idx = 0
        for m in range(M):
            per_layer = []
            for L in range(N_LAYERS):
                per_layer.append(reduced[idx])
                idx += 1
            outs.append(per_layer)
        return outs

    # Fallback: cat + all_reduce + split
    flat_tensors = []
    shapes = []
    sizes = []
    for m in range(M):
        for L in range(N_LAYERS):
            t = partials[m][L]
            shapes.append(t.shape)
            numel = 1
            for d in t.shape:
                numel *= d
            sizes.append(numel)
            flat_tensors.append(t.reshape(numel))

    big = torch.cat(flat_tensors, dim=0)
    reduced = xm.all_reduce(xm.REDUCE_SUM, big)
    parts = torch.split(reduced, sizes, dim=0)

    outs = []
    idx = 0
    for m in range(M):
        per_layer = []
        for L in range(N_LAYERS):
            per_layer.append(parts[idx].view(shapes[idx]))
            idx += 1
        outs.append(per_layer)
    return outs

