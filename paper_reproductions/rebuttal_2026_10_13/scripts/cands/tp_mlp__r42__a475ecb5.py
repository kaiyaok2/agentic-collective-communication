# Agent-evolved algorithm
def evolved_tp_mlp(partials, M, N_LAYERS, rank, world_size,
                   num_devices, cores_per_device, xm, torch, num_nodes=1):
    """
    Fully Batched Single AR: Stack all M*N_LAYERS partials into one tensor,
    perform a single all_reduce, then unpack back to [M][N_LAYERS] structure.
    """
    # Step 1: Collect all partials and their metadata
    # We need to preserve shape and dtype for reconstruction
    shapes = []
    dtypes = []
    flat_tensors = []
    
    for m in range(M):
        for L in range(N_LAYERS):
            partial = partials[m][L]
            shapes.append(partial.shape)
            dtypes.append(partial.dtype)
            # Flatten each tensor to 1D for concatenation
            flat_tensors.append(partial.reshape(-1))
    
    # Step 2: Concatenate all flattened tensors into a single 1D tensor
    # This creates one large buffer of size sum(numel(partials[m][L]))
    stacked = torch.cat(flat_tensors, dim=0)
    
    # Step 3: Single all_reduce on the batched payload
    reduced = xm.all_reduce(xm.REDUCE_SUM, stacked)
    
    # Step 4: Unpack the reduced tensor back to [M][N_LAYERS] structure
    outputs = []
    offset = 0
    idx = 0
    
    for m in range(M):
        per_layer = []
        for L in range(N_LAYERS):
            # Compute number of elements in this tensor
            numel = 1
            for dim in shapes[idx]:
                numel *= dim
            
            # Extract the slice corresponding to this (m, L) pair
            tensor_slice = reduced[offset : offset + numel]
            
            # Reshape back to original shape
            reconstructed = tensor_slice.reshape(shapes[idx])
            per_layer.append(reconstructed)
            
            offset += numel
            idx += 1
        
        outputs.append(per_layer)
    
    return outputs

