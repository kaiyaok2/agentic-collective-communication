"""
Uniform AllToAll (Fixed-Capacity MoE): Optimized implementation for AWS Trainium.

Generated by the LLM-guided algorithm evolution agent.
"""

import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_uniform_a2a():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_uniform_a2a(input_tensor, chunk_size, rank, world_size,
                        num_devices, cores_per_device, xm, torch,
                        num_nodes=1):
    """AllGather on dim=1: row `rank` is contiguous → all metadata-only ops."""
    x = input_tensor.view(world_size, chunk_size)
    gathered = xm.all_gather(x, dim=1)
    # gathered shape: [world_size, world_size * chunk_size]
    # Row `rank` contains all chunks destined to this rank, contiguous.
    return gathered[rank].view(-1)


# ================================================================
# Public API
# ================================================================

def uniform_a2a(input_tensor, chunk_size):
    """Uniform all-to-all using the agent-evolved algorithm."""
    if _rank is None:
        raise RuntimeError("Call init_uniform_a2a() first")
    return evolved_uniform_a2a(
        input_tensor, chunk_size, _rank, _world_size, _NUM_DEVICES,
        _CORES_PER_DEVICE, xm, torch, num_nodes=_NUM_NODES)

