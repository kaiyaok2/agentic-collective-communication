"""
AllToAllV: Optimized implementation for AWS Trainium.

Generated by the LLM-guided algorithm evolution agent.
"""

import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_alltoallv():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_alltoallv(input_tensor, send_counts, recv_counts, max_chunk,
                      rank, world_size, num_devices, cores_per_device,
                      xm, torch, num_nodes=1):
    """Two-level scheme: when num_nodes > 1, do an intra-node all_gather
    over the world_size*max_chunk packed payload using node-local groups,
    so the cross-node hops are only ranks_per_node*max_chunk bytes per
    permute step rather than the full payload. Falls back to one flat AG
    on single-node configurations."""
    ranks_per_node = world_size // num_nodes
    pack_size = world_size * max_chunk
    packed = torch.zeros(pack_size, device=input_tensor.device,
                         dtype=input_tensor.dtype)
    send_off = 0
    for i in range(world_size):
        sc = send_counts[i]
        if sc > 0:
            packed[i * max_chunk:i * max_chunk + sc] =                 input_tensor[send_off:send_off + sc]
        send_off += sc
    if num_nodes <= 1 or ranks_per_node <= 1:
        gathered = xm.all_gather(packed.unsqueeze(0), dim=0).view(-1)
    else:
        intra_groups = [list(range(n * ranks_per_node, (n + 1) * ranks_per_node))
                        for n in range(num_nodes)]
        gathered = xm.all_gather(packed.unsqueeze(0), dim=0,
                                 groups=intra_groups).view(-1)
    flat_idx = []
    for src in range(world_size):
        count = recv_counts[src]
        base = src * pack_size + rank * max_chunk
        flat_idx.extend(range(base, base + count))
    idx_tensor = torch.tensor(flat_idx, device=input_tensor.device,
                              dtype=torch.long)
    return torch.index_select(gathered, 0, idx_tensor)

