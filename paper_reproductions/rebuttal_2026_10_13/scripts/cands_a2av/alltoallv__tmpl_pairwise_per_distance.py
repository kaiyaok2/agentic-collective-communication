"""
AllToAllV: Optimized implementation for AWS Trainium.

Generated by the LLM-guided algorithm evolution agent.
"""

import torch
import torch_xla.core.xla_model as xm
import torch_xla.runtime as xr

_WORLD = 224
_NUM_DEVICES = 112
_NUM_NODES = 7
_CORES_PER_DEVICE = 2

_rank = None
_world_size = None


def init_alltoallv():
    """Initialize rank/world info. Call once after dist.init_process_group."""
    global _rank, _world_size
    _rank = xr.global_ordinal()
    _world_size = xr.world_size()


# Agent-evolved algorithm
def evolved_alltoallv(input_tensor, send_counts, recv_counts, max_chunk,
                      rank, world_size, num_devices, cores_per_device,
                      xm, torch, num_nodes=1):
    """W-1 rounds of collective_permute with one (rank, (rank+d)%W) pair
    per round. Each round moves one shard between every same-distance
    pair, so total bytes-per-round is max_chunk regardless of world size.
    Same algorithm family as permute_ring but iterates by distance d."""
    send_offsets = [0]
    for c in send_counts[:-1]:
        send_offsets.append(send_offsets[-1] + c)
    recv_offsets = [0]
    for c in recv_counts[:-1]:
        recv_offsets.append(recv_offsets[-1] + c)
    total_recv = sum(recv_counts)
    output = torch.zeros(total_recv, device=input_tensor.device,
                         dtype=input_tensor.dtype)
    self_count = recv_counts[rank]
    if self_count > 0:
        output[recv_offsets[rank]:recv_offsets[rank] + self_count] =             input_tensor[send_offsets[rank]:send_offsets[rank] + send_counts[rank]]
    shards = []
    for i in range(world_size):
        sc = send_counts[i]
        chunk = input_tensor[send_offsets[i]:send_offsets[i] + sc]
        if sc < max_chunk:
            chunk = torch.cat([chunk, torch.zeros(max_chunk - sc,
                              device=input_tensor.device,
                              dtype=input_tensor.dtype)])
        shards.append(chunk)
    for d in range(1, world_size):
        send_to = (rank + d) % world_size
        recv_from = (rank - d + world_size) % world_size
        pairs = [(r, (r + d) % world_size) for r in range(world_size)]
        received = xm.collective_permute(shards[send_to], pairs=pairs)
        rc = recv_counts[recv_from]
        if rc > 0:
            output[recv_offsets[recv_from]:recv_offsets[recv_from] + rc] = received[:rc]
    return output

